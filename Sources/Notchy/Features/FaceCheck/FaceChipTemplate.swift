import CoreGraphics

/// The five landmarks Face Check aligns a face with, in the order dlib's five-point template
/// lists them.
///
/// "Image left" and "image right" mean the side of the picture, not the person's own left and
/// right, so the order does not depend on whether a camera preview is mirrored.
enum FaceChipLandmark: Int, CaseIterable, Sendable {
    case imageRightEyeOuterCorner
    case imageRightEyeInnerCorner
    case imageLeftEyeOuterCorner
    case imageLeftEyeInnerCorner
    /// Where the bottom of the nose meets the upper lip, below the nose tip.
    case noseBase
}

/// Where dlib's face-recognition network expects a face to sit inside its input chip.
///
/// The network (dlib's ResNet, 128-number descriptors) was trained on 150 × 150 chips cut with
/// `get_face_chip_details(shape, 150, 0.25)`. A chip cut any other way shifts or scales the face,
/// and descriptors of the same person drift apart, so Face Check reproduces that geometry
/// exactly.
///
/// Pixel convention used throughout Face Check: origin at the image's top-left corner, y growing
/// downward, and a pixel's centre half a pixel in from its corner (the top-left pixel spans
/// 0...1 and its centre is (0.5, 0.5)). dlib puts pixel centres on whole numbers instead, so
/// converting between the two adds or removes half a pixel.
enum FaceChipTemplate {
    /// Side of the square chip the network reads, in pixels.
    static let chipSize = 150
    /// Margin dlib adds around the mean face, as a fraction of the face's own size on each side.
    static let padding = 0.25

    /// dlib's five-point mean face before padding, in unit coordinates (0...1 across the face),
    /// in `FaceChipLandmark` order.
    static let fivePointMeanFace: [CGPoint] = [
        CGPoint(x: 0.8595674595992, y: 0.2134981538014),
        CGPoint(x: 0.6460604764104, y: 0.2289674387677),
        CGPoint(x: 0.1205750620789, y: 0.2137274526848),
        CGPoint(x: 0.3340850613712, y: 0.2290642403242),
        CGPoint(x: 0.4901123135679, y: 0.6277975316475)
    ]

    /// Heights in dlib's 68-point mean face (unit coordinates before padding) of the nose tip,
    /// the nose base and the top centre of the upper lip. Only used to estimate the nose base
    /// when Vision gives no nose outline.
    static let meanNoseTipY = 0.515625
    static let meanNoseBaseY = 0.628106
    static let meanUpperLipTopY = 0.742578

    /// How far down from the nose tip towards the top of the upper lip the nose base sits in the
    /// mean face (about half way).
    static var noseBaseFractionFromTipToLip: Double {
        (meanNoseBaseY - meanNoseTipY) / (meanUpperLipTopY - meanNoseTipY)
    }

    /// The mean face moved inside the padding: unit coordinates across the whole chip.
    static func paddedUnitPoints(padding: Double = padding) -> [CGPoint] {
        fivePointMeanFace.map { point in
            CGPoint(
                x: (padding + point.x) / (2 * padding + 1),
                y: (padding + point.y) / (2 * padding + 1)
            )
        }
    }

    /// The template in chip pixels, `unit × size`: what dlib fits a face against (in its own
    /// convention, where these are pixel centres).
    static func fitPoints(size: Int = chipSize, padding: Double = padding) -> [CGPoint] {
        let side = Double(size)
        return paddedUnitPoints(padding: padding).map { CGPoint(x: $0.x * side, y: $0.y * side) }
    }

    /// The template in Face Check's chip pixel convention, `unit × size`.
    ///
    /// This is exactly where a matching face lands when it appears at the chip's own scale. A
    /// larger face lands a little closer to the chip's centre, because dlib's chip square is one
    /// pixel narrower than the fitted one (see `FaceChipAligner`): never more than half a pixel,
    /// and `FaceChipAlignment.templatePoints` has the exact spots for a given face.
    static func chipPoints(size: Int = chipSize, padding: Double = padding) -> [CGPoint] {
        fitPoints(size: size, padding: padding)
    }
}
